/**
 * Returns translation for a dotted key path (e.g. 'nav.chats') in the active or requested language.
 */
export function t(keyPath, targetLang) {
  const lang = targetLang || localStorage.getItem('nexchat_preferred_language') || 'en';
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['en'];
  const fallback = UI_TRANSLATIONS['en'];

  const parts = keyPath.split('.');
  let current = dict;
  let fallbackCurrent = fallback;

  for (const part of parts) {
    current = current ? current[part] : undefined;
    fallbackCurrent = fallbackCurrent ? fallbackCurrent[part] : undefined;
  }

  return current !== undefined ? current : (fallbackCurrent !== undefined ? fallbackCurrent : keyPath);
}

/**
 * Applies UI localization across DOM elements instantly and smoothly.
 */
export function applyUiTranslations(targetLang) {
  const lang = targetLang || localStorage.getItem('nexchat_preferred_language') || 'en';
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS['en'];

  // Set document language and text direction (RTL for Arabic)
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    if (dict.dir === 'rtl') {
      document.documentElement.dir = 'rtl';
    } else {
      document.documentElement.dir = 'ltr';
    }
  }

  // Synchronize localStorage keys
  try {
    localStorage.setItem('nexchat_preferred_language', lang);
    localStorage.setItem('nex_preferred_lang', lang);
    localStorage.setItem('nex_auto_translate_target_lang', lang);
  } catch (_) {}

  // 1. Navigation Rail & Bottom Navigation
  const navMap = [
    { id: 'nav-messages', key: 'chats' },
    { id: 'nav-status', key: 'updates' },
    { id: 'nav-reels', key: 'reels' },
    { id: 'nav-marketplace', key: 'market' },
    { id: 'nav-announcements', key: 'alerts' },
    { id: 'nav-calls', key: 'calls' },
    { id: 'nav-ai', key: 'ai' },
    { id: 'nav-groups', key: 'communities' },
    { id: 'nav-games', key: 'arcade' },
    { id: 'nav-terminal', key: 'terminal' },
    { id: 'nav-more', key: 'more' },
    { id: 'logout-btn', key: 'logout' }
  ];

  navMap.forEach(({ id, key }) => {
    const el = document.getElementById(id);
    if (!el) return;
    const label = t(`nav.${key}`, lang);
    el.title = label;
    const labelSpan = el.querySelector('.nav-label');
    if (labelSpan) labelSpan.textContent = label;
  });

  // 2. Chat Search Input & Header Inputs
  const searchInput = document.getElementById('searchInput');
  if (searchInput) searchInput.placeholder = t('search.chatsPlaceholder', lang);

  const contactsSearchInput = document.getElementById('search-input');
  if (contactsSearchInput) contactsSearchInput.placeholder = t('search.contactsPlaceholder', lang);

  const settingsSearchInput = document.getElementById('settingsSearchInput');
  if (settingsSearchInput) settingsSearchInput.placeholder = t('search.settingsPlaceholder', lang);

  // 3. Category Filter Tabs
  const filterMap = [
    { filter: 'all', key: 'all' },
    { filter: 'syndicates', key: 'syndicates' },
    { filter: 'ai-bots', key: 'aiBots' },
    { filter: 'market', key: 'market' },
    { filter: 'unread', key: 'unread' }
  ];

  filterMap.forEach(({ filter, key }) => {
    const btn = document.querySelector(`.filter-tab[data-filter="${filter}"]`);
    if (btn) btn.textContent = t(`filters.${key}`, lang);
  });

  // 4. System Action Rows (Locked chats, Archived)
  const lockedChatsLabel = document.querySelector('#lockedChatsRow .system-row-label');
  if (lockedChatsLabel) lockedChatsLabel.textContent = t('systemRows.lockedChats', lang);

  const archivedLabel = document.querySelector('#archivedToggleRow .system-row-label');
  if (archivedLabel) archivedLabel.textContent = t('systemRows.archived', lang);

  const emptyArchived = document.querySelector('#archivedList .empty-state p');
  if (emptyArchived) emptyArchived.textContent = t('systemRows.noArchived', lang);

  // 5. Empty Chat State
  const emptyChatTitle = document.querySelector('#contactList .empty-state p');
  if (emptyChatTitle) emptyChatTitle.textContent = t('chat.noChats', lang);

  const emptyChatHint = document.querySelector('#contactList .empty-state .hint');
  if (emptyChatHint) emptyChatHint.textContent = t('chat.searchHint', lang);

  // 6. Chat Welcome Panel
  const welcomeH2 = document.querySelector('#chatWelcomePanel h2');
  if (welcomeH2) welcomeH2.textContent = t('chat.selectConversation', lang);

  const welcomeP = document.querySelector('#chatWelcomePanel p');
  if (welcomeP) welcomeP.textContent = t('chat.welcomeHint', lang);

  // 7. Message Composer Textarea & Action Buttons
  const messageInput = document.getElementById('message-input');
  if (messageInput) messageInput.placeholder = t('composer.placeholder', lang);

  const sendBtn = document.getElementById('send-btn');
  if (sendBtn) sendBtn.title = t('composer.send', lang);

  const voiceBtn = document.getElementById('voice-record-btn');
  if (voiceBtn) voiceBtn.title = t('composer.voice', lang);

  const attachBtn = document.getElementById('btnToggleAttachmentHub');
  if (attachBtn) attachBtn.title = t('composer.attachment', lang);

  const aiPolishBtn = document.getElementById('aiPolishInputBtn');
  if (aiPolishBtn) aiPolishBtn.title = t('composer.aiPolish', lang);

  const autocorrectBtn = document.getElementById('quickAutocorrectBtn');
  if (autocorrectBtn) {
    const span = autocorrectBtn.querySelector('span');
    if (span) span.textContent = t('composer.autoCorrect', lang);
  }

  // 8. Settings Navigation Tabs
  if (dict.settingsTabs) {
    Object.entries(dict.settingsTabs).forEach(([tabId, labelText]) => {
      const tabBtn = document.querySelector(`.settings-nav-tab[data-tab="${tabId}"]`);
      if (tabBtn) {
        const textSpan = tabBtn.querySelector('span:first-of-type');
        if (textSpan && !textSpan.classList.contains('settings-tab-microbadge')) {
          textSpan.textContent = labelText;
        }
      }
    });
  }

  // 9. Sync Dropdowns in DOM
  const primarySelect = document.getElementById('settingsPrimaryLangSelect');
  if (primarySelect && primarySelect.value !== lang) {
    primarySelect.value = lang;
  }

  const autoTranslateSelect = document.getElementById('autoTranslateTargetLangSelect');
  if (autoTranslateSelect && autoTranslateSelect.value !== lang) {
    autoTranslateSelect.value = lang;
  }

  const modalSelect = document.getElementById('translateTargetLang');
  if (modalSelect && modalSelect.value !== lang) {
    modalSelect.value = lang;
  }

  const currentBadge = document.getElementById('settingsCurrentLangBadge');
  if (currentBadge && dict.native) {
    currentBadge.textContent = `${dict.native} (${dict.name})`;
  }

  const predictiveBadge = document.getElementById('predictiveLangBadge');
  if (predictiveBadge) {
    predictiveBadge.textContent = lang.toUpperCase();
    predictiveBadge.title = `Current Language: ${dict.native} (${dict.name})`;
  }

  // 10. Update CyberFeatures Translator instance
  if (typeof window !== 'undefined' && window.CyberFeatures && window.CyberFeatures.translator) {
    window.CyberFeatures.translator.autoTranslateTargetLang = lang;
    window.CyberFeatures.translator.preferredLang = lang;
    if (typeof window.CyberFeatures.translator.updateChatHeaderBadge === 'function') {
      window.CyberFeatures.translator.updateChatHeaderBadge();
    }
    if (typeof window.CyberFeatures.translator.clearAutoTranslateCacheAndRescan === 'function' &&
        window.CyberFeatures.translator.isAutoTranslateActiveForCurrentChat()) {
      window.CyberFeatures.translator.clearAutoTranslateCacheAndRescan();
    }
  }

  // 11. Custom data-i18n Attribute Elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (key) el.textContent = t(key, lang);
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.placeholder = t(key, lang);
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.title = t(key, lang);
  });

  // 12. Dispatch custom event for dynamic components
  try {
    window.dispatchEvent(new CustomEvent('nexchat:languageChanged', { detail: { lang } }));
  } catch (_) { }

  console.log(`[i18n] UI successfully localized to: ${lang}`);
}

// Auto-initialize on window load
if (typeof window !== 'undefined') {
  window.NEX_I18N = {
    t,
    applyUiTranslations,
    UI_TRANSLATIONS
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', () => {
      applyUiTranslations();
    });
  } else {
    applyUiTranslations();
  }
}
