  const RU_WORD_SET = new Set(RU_WORDS.map(w => w.toLowerCase()));
  const CYRILLIC_REGEX = /[\u0400-\u04FF]/;

  /**
   * Russian Sub-Directory Engine
   */
  class RussianSubDirectory {
    constructor() {
      this.name = 'Russian (Русский)';
      this.code = 'ru';
      this.wordSet = RU_WORD_SET;
      this.typoMap = RU_TYPO_MAP;
      this.adjacent = RU_JCUKEN_ADJACENT;
      this.isActive = false;
    }

    /**
     * Checks if a word is in the Russian dictionary
     */
    hasWord(word) {
      if (!word) return false;
      const clean = word.toLowerCase().replace(/[^а-яё-]/g, '');
      return this.wordSet.has(clean);
    }

    /**
     * Checks if text contains Cyrillic characters
     */
    detect(text) {
      if (!text || typeof text !== 'string') return false;
      return CYRILLIC_REGEX.test(text);
    }

    /**
     * Corrects a Russian typo in 0ms O(1)
     */
    correctWord(cleanWord) {
      if (!cleanWord) return null;
      return this.typoMap[cleanWord] || null;
    }

    /**
     * Cyrillic JCUKEN Fuzzy Distance Matcher
     */
    findFuzzyMatch(word, maxDistance = 1.5) {
      if (!word || word.length < 3) return null;
      if (this.typoMap[word]) return this.typoMap[word];
      if (this.wordSet.has(word)) return word;

      let bestWord = null;
      let minScore = maxDistance;

      for (const candidate of this.wordSet) {
        if (Math.abs(candidate.length - word.length) > 1) continue;
        if (candidate[0] !== word[0]) continue; // First letter match

        let diff = 0;
        const maxLen = Math.max(word.length, candidate.length);

        for (let i = 0; i < maxLen; i++) {
          const c1 = word[i] || '';
          const c2 = candidate[i] || '';
          if (c1 === c2) continue;

          // Check JCUKEN adjacency
          if (this.adjacent[c1] && this.adjacent[c1].includes(c2)) {
            diff += 0.5; // Fat-finger adjacent key cost
          } else {
            diff += 1.0;
          }
        }

        if (diff < minScore) {
          minScore = diff;
          bestWord = candidate;
        }
      }

      return bestWord;
    }

    activate() {
      this.isActive = true;
      if (typeof window !== 'undefined') {
        window.RU_SUBDIRECTORY_ACTIVE = true;
      }
    }

    deactivate() {
      this.isActive = false;
      if (typeof window !== 'undefined') {
        window.RU_SUBDIRECTORY_ACTIVE = false;
      }
    }
  }

